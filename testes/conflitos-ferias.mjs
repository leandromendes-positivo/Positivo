import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync('src/js/69-ferias.js','utf8'),ctx);
const pessoa=(id,localidade='capital',extra={})=>({id,matricula:id,regiao:'PR',area:'tecnico',localidade,status:'planejado',periodos:[{inicio:'2027-01-10',fim:'2027-01-29'}],...extra});
const conflitos=(a,b)=>ctx.conflitosFerias(a,[a,b]).length;
const capital=pessoa('capital'),interior=pessoa('interior','interior');
assert.equal(conflitos(capital,interior),0);assert.equal(conflitos(interior,capital),0);
assert.equal(conflitos(capital,pessoa('outra-capital')),1);
assert.equal(conflitos(interior,pessoa('outro-interior','interior')),1);
assert.equal(conflitos(capital,pessoa('sem-localidade','')),1);
assert.equal(conflitos(capital,pessoa('outra-uf','capital',{regiao:'SC'})),0);
assert.equal(conflitos(capital,pessoa('outra-data','capital',{periodos:[{inicio:'2027-01-01',fim:'2027-01-09'}]})),0);
assert.equal(conflitos(capital,pessoa('limite','capital',{periodos:[{inicio:'2027-01-29',fim:'2027-02-10'}]})),1);
assert.equal(conflitos(capital,pessoa('cancelado','capital',{status:'cancelado'})),0);
assert.equal(conflitos(capital,pessoa('arquivado','capital',{arquivado:true})),0);
assert.equal(conflitos(capital,{...capital,id:'outro-ciclo'}),0);
const legado=(id,regiao)=>{const f=pessoa(id,undefined,{regiao});delete f.area;delete f.localidade;return f;};
assert.equal(conflitos(legado('a','PR Capital'),legado('b','PR Interior')),0);
assert.equal(conflitos(legado('a','PR Capital'),legado('b','PR Capital')),1);
assert.equal(conflitos(pessoa('adm','',{area:'administrativo'}),pessoa('adm2','',{area:'administrativo'})),1);
const administrativo=pessoa('administrativo','',{area:'administrativo'});
for(const tecnico of [capital,interior,pessoa('sem-localidade',''),legado('legado','PR Capital')]){assert.equal(conflitos(administrativo,tecnico),0);assert.equal(conflitos(tecnico,administrativo),0);}
assert.equal(conflitos(administrativo,pessoa('adm-outra-uf','',{area:'administrativo',regiao:'SC'})),0);
console.log('Conflitos: capital/interior separados, mesma localidade, dados legados, localidade ausente, UF, datas, cancelamento e arquivo passaram.');
