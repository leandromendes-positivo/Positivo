import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx=vm.createContext({E:{novas:[],usadas:[]},prazoDoTecnico:()=>7});
vm.runInContext(fs.readFileSync('src/js/00-util.js','utf8')+'\n'+fs.readFileSync('src/js/40-importacao.js','utf8'),ctx);
const item=(mat='100',tecChave='ANA',tipoEnvio='BACKUP')=>({mat,tecChave,tipoEnvio,qtd:2});
const foto=(dia,itens,novas=[],regiao='PR')=>ctx.compararFoto({tipo:'novas',regiao,itens},dia,dia+' 12:00','L-'+dia,{novas});
const dias=(linha,dia)=>ctx.diasComPecaNova(linha.desde,dia);
const primeira=foto('2026-11-10',[item()]);
assert.equal(dias(primeira.linhas[0],'2026-11-10'),1);
const repetida=foto('2026-11-10',[item()],primeira.linhas);
assert.equal(dias(repetida.linhas[0],'2026-11-10'),1,'reenviar no mesmo dia não soma dias');
const amanha=foto('2026-11-11',[item()],repetida.linhas);
assert.equal(amanha.linhas[0].desde,'2026-11-10');assert.equal(dias(amanha.linhas[0],'2026-11-11'),2);
const mudouTipo=foto('2026-11-12',[item('100','ANA','PP')],amanha.linhas);
assert.equal(dias(mudouTipo.linhas[0],'2026-11-12'),3);assert.equal(mudouTipo.movimentos.length,0,'troca do tipo de envio não representa uma saída física');
const saiu=foto('2026-11-13',[],mudouTipo.linhas);
assert.equal(saiu.movimentos[0].dias,4,'a saída guarda a contagem encerrada');
assert.equal(saiu.movimentos[0].contagemDesde,'2026-11-10');
const voltou=foto('2026-11-14',[item()],saiu.linhas);
assert.equal(dias(voltou.linhas[0],'2026-11-14'),1,'reaparecer após uma ausência inicia nova permanência');
assert.equal(dias(voltou.linhas[0],'2026-11-16'),3,'dias civis, inclusive quando há intervalo entre relatórios');
assert.equal(dias(foto('2026-11-11',[item('100','BRUNO')],amanha.linhas).linhas[0],'2026-11-11'),1,'outro técnico tem sua própria contagem');
assert.equal(dias(foto('2026-11-11',[item()],amanha.linhas,'SC').linhas[0],'2026-11-11'),1,'outra UF tem sua própria contagem');
const legado=foto('2026-11-10',[item()],[{...primeira.linhas[0],desde:'2026-10-01'}]).linhas[0];
assert.equal(legado.desde,'2026-10-01','a data histórica original é preservada');
assert.equal(ctx.inicioContagemNova(legado.desde,'2026-11-10'),'2026-11-10');assert.equal(dias(legado,'2026-11-10'),1);
assert.equal(ctx.diasComPecaNova('2026-11-01','2026-11-09'),8,'eventos anteriores à ativação preservam sua contagem');
assert.equal(ctx.diasComPecaNova('2026-12-31','2027-01-01'),2,'virada de mês e ano');
ctx.window={__CP_AGORA:'2026-11-18T12:00:00-03:00'};ctx.nomeTecnico=tid=>tid;ctx.prazoDaDevolucao=()=>7;
vm.runInContext(fs.readFileSync('src/js/31-analises.js','utf8'),ctx);
const historico=movimento=>ctx.calcularDesempenho({tipo:'novas',periodo:'intervalo',inicio:'2026-11-10',fim:'2026-11-10',historico:{devolucoes:[],movimentos:[movimento]}},{hoje:'2026-11-18',cfg:{prazoNovas:7},itens:[],tecnicos:[]});
const antiga={tid:'ANA',regiao:'PR',mat:'100',qtd:1,desde:'2026-11-01',em:'2026-11-10 09:00',dias:9,prazo:7,destino:'devolucao'};
assert.equal(historico(antiga).lista[0].atrasadas,1,'saídas já registradas antes da ativação mantêm sua base histórica');
assert.equal(historico({...antiga,contagemDesde:'2026-11-10',dias:1}).lista[0].noPrazo,1,'saídas da nova contagem usam o primeiro relatório acompanhado');
console.log('Tempo com peças novas: dia 1, continuidade, reenvio, troca de envio, técnico/UF, saída, retorno, legado e virada de ano passaram.');
